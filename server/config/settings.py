#
# Provide: $env:DATABASE_URL="postgresql://user:pass@ep-xxx.neon.tech/dbname?sslmode=require"
# or server/.env containing: DATABASE_URL=postgresql://...

_DATABASE_URL = os.environ.get("DATABASE_URL", "").strip()
if not _DATABASE_URL:
    raise ImproperlyConfigured(
        "DATABASE_URL is not set. Set $env:DATABASE_URL or server/.env "
        "to a postgresql:// URL before running check/migrate/test/runserver."
    )

_parsed_db = urlparse(_DATABASE_URL)
if _parsed_db.scheme not in ("postgres", "postgresql"):
    raise ImproperlyConfigured("DATABASE_URL must start with postgres:// or postgresql://.")

_db_query = dict(parse_qsl(_parsed_db.query, keep_blank_values=True))
_db_query.setdefault("sslmode", "require")

